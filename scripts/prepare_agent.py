"""Package the shared platform source into the standalone app deployment directory.

Edit databricks/platform, not the generated copy. Run before every Agent Bricks deployment.
"""
from pathlib import Path
import shutil

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'databricks/platform'
target=ROOT/'databricks/magneto-director'
shutil.copytree(source/'magneto_platform', target/'magneto_platform', dirs_exist_ok=True,
                ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
shutil.copyfile(source/'services.toml', target/'services.toml')
(target/'magneto_platform/GENERATED.txt').write_text('Generated by scripts/prepare_agent.py from databricks/platform. Do not edit this deployment copy.\n')
print('Packaged shared service adapters and services.toml for deployment.')

catalog = ROOT / 'databricks/contracts/v3/activity-catalog.json'
shutil.copyfile(catalog, target / 'learning/activity-catalog.json')
(ROOT / 'web/learn/activity-catalog.js').write_text(
    '// Generated from databricks/contracts/v3/activity-catalog.json by scripts/prepare_agent.py.\n'
    + 'export const ACTIVITY_CATALOG = ' + catalog.read_text().strip() + ';\n')
